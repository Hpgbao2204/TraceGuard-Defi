import json
import unittest
from pathlib import Path


class TestE5PreflightArtifact(unittest.TestCase):
    def test_preflight_is_not_a_verdict(self):
        path = Path("eval/results/e5_rcfh/e4_candidate_preflight.json")
        if not path.exists():
            self.skipTest("preflight is generated by the phase runner")
        data = json.loads(path.read_text())
        self.assertTrue(all(x["causal_verdict"] is None for x in data["cases"]))
        self.assertTrue(all(x["counterfactual_replay"] == "NOT_RUN" for x in data["cases"]))


if __name__ == "__main__": unittest.main()
